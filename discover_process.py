from pathlib import Path
import argparse
import pandas as pd
import pm4py

REQUIRED_COLUMNS = ["case_id", "activity", "timestamp"]

COLUMN_ALIASES = {
    "case_id": ["case_id", "visit_id", "case", "caseid", "encounter_id"],
    "activity": ["activity", "event", "activity_name", "event_name"],
    "timestamp": ["timestamp", "time", "event_time", "datetime"],
}


def resolve_columns(df, overrides):
    """Rename the file's own columns to case_id / activity / timestamp.
    overrides: {"case_id": name or None, ...} from the command line."""
    lower = {str(c).strip().lower(): c for c in df.columns}
    rename = {}
    for target, aliases in COLUMN_ALIASES.items():
        chosen = overrides.get(target)
        if chosen:
            if chosen not in df.columns:
                raise ValueError(f"Column '{chosen}' not found. Available: {list(df.columns)}")
            source = chosen
        else:
            source = next((lower[a] for a in aliases if a in lower), None)
        if source is not None and source != target:
            rename[source] = target
    if rename:
        print("Using column mapping:", {v: k for k, v in rename.items()})
    return df.rename(columns=rename)



def main():
    parser = argparse.ArgumentParser(
        description="Discover the CareFlow patient process using PM4Py."
    )
    parser.add_argument(
        "--input",
        default="event_log_ED_MMA_2026.csv",
        help="Path to the prepared event-log CSV"
    )
    parser.add_argument(
        "--output-dir",
        default="pm_outputs",
        help="Folder for generated outputs"
    )
    parser.add_argument("--case-col", default=None, help="Case ID column (auto-detects case_id/visit_id)")
    parser.add_argument("--activity-col", default=None, help="Activity column (auto-detects activity/event)")
    parser.add_argument("--time-col", default=None, help="Timestamp column (auto-detects timestamp)")

    # Use parse_known_args() so that background Jupyter/Colab flags do not raise errors
    args, unknown = parser.parse_known_args()

    input_path = Path(args.input)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    if not input_path.exists():
        raise FileNotFoundError(
            f"Dataset not found: {input_path.resolve()}. "
            "Pass the correct path using --input."
        )

    df = pd.read_csv(input_path)
    df = resolve_columns(df, {"case_id": args.case_col, "activity": args.activity_col,
                              "timestamp": args.time_col})

    missing = [col for col in REQUIRED_COLUMNS if col not in df.columns]
    if missing:
        raise ValueError(f"Required columns are missing: {missing}")

    # Normalize fields used by process mining.
    df["case_id"] = df["case_id"].astype("string").str.strip()
    df["activity"] = df["activity"].astype("string").str.strip()
    df["timestamp"] = pd.to_datetime(
        df["timestamp"], errors="coerce", utc=True
    )

    invalid_rows = (
        df["case_id"].isna()
        | df["activity"].isna()
        | df["timestamp"].isna()
        | df["case_id"].eq("")
        | df["activity"].eq("")
    )

    print("Rows with missing/invalid required values:", int(invalid_rows.sum()))
    df = df.loc[~invalid_rows].copy()

    if df.empty:
        raise ValueError("No valid events remain after validation.")

    # Use sequence to break timestamp ties when available.
    sort_columns = ["case_id", "timestamp"]
    if "sequence" in df.columns:
        sort_columns.append("sequence")

    df = df.sort_values(sort_columns, kind="stable")

    if df["case_id"].nunique() < 1:
        raise ValueError("No valid cases found.")

    # Convert the dataframe to PM4Py's event-log format.
    event_log = pm4py.format_dataframe(
        df,
        case_id="case_id",
        activity_key="activity",
        timestamp_key="timestamp"
    )

    # Discover a process model from the observed event log.
    net, initial_marking, final_marking = (
        pm4py.discover_petri_net_inductive(event_log)
    )

    output_file = output_dir / "careflow_process_map.png"

    pm4py.save_vis_petri_net(
        net,
        initial_marking,
        final_marking,
        str(output_file)
    )

    print("\nProcess discovery completed.")
    print("Valid event rows:", len(df))
    print("Distinct cases:", df["case_id"].nunique())
    print("Distinct activities:", df["activity"].nunique())
    print("Process map:", output_file.resolve())


if __name__ == "__main__":
    main()