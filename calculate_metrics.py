# calculate_metrics.py

from pathlib import Path
import argparse
import pandas as pd
import sys

REQUIRED_COLUMNS = ["case_id", "activity", "timestamp"]


def main():
    parser = argparse.ArgumentParser(
        description="Calculate CareFlow pathway and transition metrics."
    )
    parser.add_argument(
        "--input",
        default="careflow_event_log.csv",
        help="Path to the prepared event-log CSV"
    )
    parser.add_argument(
        "--output-dir",
        default="pm_outputs",
        help="Folder for generated CSV outputs"
    )

    # Check if running inside a Jupyter/Colab notebook to prevent argparse errors with kernel arguments
    if "ipykernel" in sys.modules:
        args = parser.parse_args(args=[])
    else:
        args = parser.parse_args()

    input_path = Path(args.input)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    if not input_path.exists():
        raise FileNotFoundError(
            f"Dataset not found: {input_path.resolve()}. "
            "Pass the correct path using --input."
        )

    df = pd.read_csv(input_path)

    missing = [col for col in REQUIRED_COLUMNS if col not in df.columns]
    if missing:
        raise ValueError(f"Required columns are missing: {missing}")

    df["case_id"] = df["case_id"].astype("string").str.strip()
    df["activity"] = df["activity"].astype("string").str.strip()
    df["timestamp"] = pd.to_datetime(
        df["timestamp"], errors="coerce", utc=True
    )

    invalid = (
        df["case_id"].isna()
        | df["activity"].isna()
        | df["timestamp"].isna()
        | df["case_id"].eq("")
        | df["activity"].eq("")
    )

    print("Invalid rows excluded:", int(invalid.sum()))
    df = df.loc[~invalid].copy()

    if df.empty:
        raise ValueError("No valid events remain after validation.")

    sort_columns = ["case_id", "timestamp"]
    if "sequence" in df.columns:
        sort_columns.append("sequence")

    df = df.sort_values(sort_columns, kind="stable").reset_index(drop=True)

    # --------------------------------------------------
    # 1. PATHWAY FREQUENCIES
    # Each case contributes its ordered activity sequence.
    # --------------------------------------------------
    case_paths = (
        df.groupby("case_id", sort=False)["activity"]
        .agg(list)
        .reset_index(name="activities")
    )

    case_paths["pathway"] = case_paths["activities"].apply(
        lambda activities: " -> ".join(activities)
    )

    pathway_frequencies = (
        case_paths.groupby("pathway")
        .size()
        .reset_index(name="case_count")
        .sort_values("case_count", ascending=False)
        .reset_index(drop=True)
    )

    total_cases = case_paths["case_id"].nunique()
    pathway_frequencies["case_percent"] = (
        pathway_frequencies["case_count"] / total_cases * 100
    ).round(2)

    pathway_frequencies.to_csv(
        output_dir / "pathway_frequencies.csv", index=False
    )

    # --------------------------------------------------
    # 2. TRANSITION METRICS
    # Compare each event with the next event in the same case.
    # --------------------------------------------------
    df["next_activity"] = df.groupby("case_id")["activity"].shift(-1)
    df["next_timestamp"] = df.groupby("case_id")["timestamp"].shift(-1)

    transitions = df.loc[df["next_activity"].notna()].copy()

    transitions["elapsed_minutes"] = (
        transitions["next_timestamp"] - transitions["timestamp"]
    ).dt.total_seconds() / 60

    # Negative time intervals are invalid and excluded from time statistics.
    valid_times = transitions.loc[
        transitions["elapsed_minutes"].ge(0)
    ].copy()

    transition_counts = (
        transitions.groupby(["activity", "next_activity"])
        .size()
        .reset_index(name="transition_count")
        .rename(columns={
            "activity": "from_activity",
            "next_activity": "to_activity"
        })
    )

    time_stats = (
        valid_times.groupby(["activity", "next_activity"])["elapsed_minutes"]
        .agg(
            valid_time_count="count",
            average_minutes="mean",
            median_minutes="median"
        )
        .reset_index()
        .rename(columns={
            "activity": "from_activity",
            "next_activity": "to_activity"
        })
    )

    transition_metrics = transition_counts.merge(
        time_stats,
        on=["from_activity", "to_activity"],
        how="left"
    )

    transition_metrics["average_minutes"] = (
        transition_metrics["average_minutes"].round(2)
    )
    transition_metrics["median_minutes"] = (
        transition_metrics["median_minutes"].round(2)
    )

    transition_metrics = transition_metrics.sort_values(
        "transition_count", ascending=False
    )

    transition_metrics.to_csv(
        output_dir / "transition_metrics.csv", index=False
    )

    # --------------------------------------------------
    # 3. CASE-LEVEL METRICS
    # Duration is first recorded event to last recorded event.
    # --------------------------------------------------
    case_metrics = (
        df.groupby("case_id")
        .agg(
            event_count=("activity", "size"),
            unique_activities=("activity", "nunique"),
            first_event=("timestamp", "min"),
            last_event=("timestamp", "max")
        )
        .reset_index()
    )

    case_metrics["observed_duration_minutes"] = (
        (case_metrics["last_event"] - case_metrics["first_event"])
        .dt.total_seconds() / 60
    ).round(2)

    case_metrics.to_csv(
        output_dir / "case_metrics.csv", index=False
    )

    print("\nAnalysis completed successfully.")
    print("Valid events:", len(df))
    print("Distinct cases:", total_cases)
    print("Distinct activities:", df["activity"].nunique())
    print("Unique pathways:", len(pathway_frequencies))
    print("Distinct transitions:", len(transition_metrics))
    print("Outputs saved in:", output_dir.resolve())


if __name__ == "__main__":
    main()